test("free combinations, saved component choices and switching back to registration groups",async({page})=>{
 await page.goto("/");
 await page.getByRole("textbox",{name:"חיפוש קורס לפי שם או מספר"}).fill("234124");
 await page.getByRole("button",{name:"הוספת קורס 02340124"}).click();
 await page.goto("/planner");
 const mode=page.getByRole("checkbox",{name:"לשמור על קבוצות הרישום"});
 await expect(mode).not.toBeChecked();
 const lecture=page.getByLabel("הרצאה מבוא לתכנות מערכות",{exact:true});
 const tutorial=page.getByLabel("תרגול מבוא לתכנות מערכות",{exact:true});
 await lecture.selectOption({label:"הרצאה 20 · 1 מפגשים"});
 await tutorial.selectOption({label:"תרגול 11 · 1 מפגשים"});
 const pickedLecture=await lecture.inputValue(),pickedTutorial=await tutorial.inputValue();
 await page.reload();
 await expect(lecture).toHaveValue(pickedLecture);
 await expect(tutorial).toHaveValue(pickedTutorial);
 await mode.check();
 await expect(page.getByLabel("קבוצת רישום מבוא לתכנות מערכות")).toBeVisible();
 await mode.uncheck();
 await expect(lecture).toHaveValue(pickedLecture);
 await page.getByText("אפשרויות מותרות ליצירה אוטומטית",{exact:true}).click();
 const lectureChoices=page.locator(".component-allowlist").filter({has:page.locator("strong").filter({hasText:/^הרצאה$/})});
 const tutorialChoices=page.locator(".component-allowlist").filter({has:page.locator("strong").filter({hasText:/^תרגול$/})});
 for(const checkbox of await lectureChoices.getByRole("checkbox").all())await checkbox.uncheck();
 for(const checkbox of await tutorialChoices.getByRole("checkbox").all())await checkbox.uncheck();
 await lectureChoices.getByRole("checkbox",{name:"הרצאה 20",exact:true}).check();
 await tutorialChoices.getByRole("checkbox",{name:"תרגול 11",exact:true}).check();
 await page.getByRole("button",{name:"יצירת מערכות חכמות"}).click();
 await expect(page).toHaveURL("/schedules");
 await expect(page.locator(".result-card")).toHaveCount(1);
 await expect(page.locator(".chosen-summary")).toContainText("הרצאה 20");
 await expect(page.locator(".chosen-summary")).toContainText("תרגול 11");
 await expect(page.locator(".calendar-panel .badge")).toContainText("ללא חפיפות");
 await page.getByRole("button",{name:"שמירה כמערכת שלי"}).click();
 await page.reload();
 await expect(page.getByLabel("הרצאה מבוא לתכנות מערכות",{exact:true})).toHaveValue(pickedLecture);
 await expect(page.getByLabel("תרגול מבוא לתכנות מערכות",{exact:true})).toHaveValue(pickedTutorial);
});
